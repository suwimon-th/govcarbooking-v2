// Generate explicit selectors for the color utilities used by this application.
// Saturated vehicle colors, white text and dark brand backgrounds are deliberately preserved.
const fs = require('node:fs');
const path = require('node:path');
function files(dir) { return fs.readdirSync(dir,{withFileTypes:true}).flatMap(e=>e.isDirectory()?files(path.join(dir,e.name)):/\.(tsx|ts)$/.test(e.name)?[path.join(dir,e.name)]:[]); }
const source = files('app').concat(files('lib')).map(p=>fs.readFileSync(p,'utf8')).join('\n');
const tokens = [...new Set(source.match(/(?:hover:|focus:|group-hover:)?(?:bg|text|border|from|via|to|divide|shadow|placeholder)-(?:white|black|(?:slate|gray|zinc|neutral|stone|blue|indigo|sky|cyan|teal|emerald|green|lime|yellow|amber|orange|red|rose|pink|purple|violet)-(?:50|100|200|300|400|500|600|700|800|900|950))(?:\/\d+)?/g))].sort();
const hues={blue:['#203957','#a9ceff'],indigo:['#303251','#c2c5ff'],sky:['#153b50','#9bdeff'],cyan:['#153b45','#9be4ed'],teal:['#183d3b','#96e3d5'],emerald:['#193d31','#96e1ba'],green:['#223d2c','#ace3b3'],lime:['#323e25','#cfdf9c'],yellow:['#403b20','#f1de96'],amber:['#423421','#f8d49a'],orange:['#432e22','#ffc4a0'],red:['#442a30','#ffb0b8'],rose:['#432a36','#ffb2ca'],pink:['#422c40','#f6b5dc'],purple:['#382e4c','#dbbeff'],violet:['#322e4d','#cfc0ff']};
const rules=[];
for(const token of tokens){
 const match=token.match(/^(?:(hover|focus|group-hover):)?(bg|text|border|from|via|to|divide|shadow|placeholder)-(white|black|[a-z]+)(?:-(\d+))?(?:\/(\d+))?$/);if(!match)continue;
 const [,pseudo,kind,hue,shadeRaw,opacity]=match;const shade=Number(shadeRaw); const pair=hues[hue];let color;
 if(['bg','from','via','to'].includes(kind)){
   if(hue==='white' && (!opacity||Number(opacity)>=40)) color='#1b2739';
   else if(shade<=200&&shade>0)color=pair?pair[0]:shade===50?'#152033':'#223148';
 }else if(['text','placeholder'].includes(kind)&&shade>=400){color=pair?pair[1]:shade>=700?'#e2e8f0':'#afbdd0';}
 else if(['border','divide'].includes(kind)&&shade<=400&&shade>0)color=pair?pair[0]:'#3b4b62';
 else if(kind==='shadow'&&shade>0)color='#00000030';
 if(!color)continue;
 let selector=`html[data-theme="dark"] [class~="${token}"]`;
 if(pseudo==='hover'||pseudo==='focus')selector+=':'+pseudo;
 if(pseudo==='group-hover')selector=`html[data-theme="dark"] .group:hover [class~="${token}"]`;
 if(kind==='placeholder')selector+='::placeholder';
 if(kind==='divide')selector+=' > :not(:last-child)';
 const property={bg:'background-color',text:'color',border:'border-color',divide:'border-color',placeholder:'color',from:'--tw-gradient-from',via:'--tw-gradient-via',to:'--tw-gradient-to',shadow:'--tw-shadow-color'}[kind];
 rules.push(`  ${selector} { ${property}: ${color}; }`);
}
fs.writeFileSync('app/dark-palette.css','/* Generated by scripts/generate-dark-palette.cjs. Screen-only; preserves printed documents. */\n@media screen {\n'+rules.join('\n')+'\n}\n');
console.log(`Generated ${rules.length} dark-theme color rules`);
